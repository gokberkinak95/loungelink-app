// MVP isim formati: "Mert Aydin" -> "Mert A."  ·  "Elif" -> "Elif"
// Kayit sirasinda profil adi e-posta onekinden gelebiliyor (gokberkinak95 gibi);
// o durumda da okunabilir hale getirir. Canli APP 16.
export function shortName(n) {
  const raw = String(n || "").trim();
  if (!raw) return "—";
  // e-posta ya da e-posta oneki gibi gorunuyorsa: nokta/alt tire/rakamlari ayikla
  let base = raw.includes("@") ? raw.split("@")[0] : raw;
  if (!base.includes(" ") && /[._\-0-9]/.test(base)) {
    base = base.replace(/[0-9]+/g, "").replace(/[._\-]+/g, " ").trim();
  }
  const parts = base.split(/\s+/).filter(Boolean);
  if (parts.length === 0) return raw;
  const cap = (w) => w.charAt(0).toLocaleUpperCase("tr") + w.slice(1);
  if (parts.length === 1) return cap(parts[0]);
  return cap(parts[0]) + " " + parts[parts.length - 1].charAt(0).toLocaleUpperCase("tr") + ".";
}

// MVP tarih formatı: "15 Haziran 2026" (Host Bul başlığı, seyahat kartları,
// Yayın & Davet slot satırı). ISO (YYYY-MM-DD) alır; bozuksa olduğu gibi döner.
const MONTHS_TR = ["Ocak","Şubat","Mart","Nisan","Mayıs","Haziran","Temmuz","Ağustos","Eylül","Ekim","Kasım","Aralık"];
const MONTHS_EN = ["January","February","March","April","May","June","July","August","September","October","November","December"];
export function fmtLongDate(iso, lang) {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(String(iso || ""));
  if (!m) return String(iso || "");
  const months = lang === "en" ? MONTHS_EN : MONTHS_TR;
  // 🔴 3 Eylül — TASARIM (02/14): "4 Eylül", "16 Ekim" — yıl yazılmıyor.
  // Yıl yalnız BAŞKA bir yıl ise eklenir ("24 Ekim 2027"); bu yılın
  // tarihlerinde yıl bir bilgi değil, satırı uzatan bir tekrardır.
  const buYil = String(new Date().getFullYear());
  return `${parseInt(m[3], 10)} ${months[parseInt(m[2], 10) - 1]}${m[1] === buYil ? "" : " " + m[1]}`;
}
