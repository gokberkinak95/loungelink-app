//
// `BUYUK(s)` etkin dile göre doğru olanı yapar. Etkin dil `dilAyarla()` ile
// bir kez set edilir (App.js `applyLang` içinde) — böylece 16 çağrı yerinin
// hiçbirine `lang` prop'u geçirmek gerekmiyor.
// ============================================================================
let _etkinDil = "tr";
export function dilAyarla(l) { _etkinDil = (l === "en") ? "en" : "tr"; return _etkinDil; }
export function etkinDil() { return _etkinDil; }
export function BUYUK(s) {
  const v = String(s == null ? "" : s);
  return _etkinDil === "en" ? v.toUpperCase() : v.toLocaleUpperCase("tr-TR");
}

