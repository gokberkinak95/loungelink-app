// Sunucudan gelen hata KODUNU (date_in_past gibi) kullanıcının diline çevirir.
// Supabase mesajı "date_in_past" ya da "... date_in_past" biçiminde gelebilir.
// 🔴 v2.80 — SINIRA TAKILAN KULLANICI "NE ZAMAN" SORUSUNU SORUYOR.
// Gökberk: "kullanıcı sınıra eriştiyse artık neden yapamayacağına dair
// bilgilendirme metni görmeli... gece 00:00 sonrası hak yenileniyor mu?"
//
// Sunucu artık yenilenme anını hatanın `hint` alanında taşıyor
// (SQL 223: `hint = 'yenilenme=<iso>;islem=<anahtar>'`). PostgREST bu
// alanı istemciye aynen geçiriyor ama biz bugüne kadar YALNIZCA
// `error.message`'a bakıyorduk — yani sunucu cevabı gönderiyordu, app
// çöpe atıyordu.
//
// Saat TÜRKİYE saatiyle yazılıyor: sunucu UTC çalışıyor ve "gece yarısı"
// demek kullanıcı için 03:00 demek olurdu.
export function yenilenmeSaati(hata, lang) {
  const ip = hata && (hata.hint || hata.details);
  if (!ip) return null;
  const m = /yenilenme=([^;]+)/.exec(String(ip));
  if (!m) return null;
  const d = new Date(m[1].trim());
  if (isNaN(d.getTime())) return null;
  try {
    return new Intl.DateTimeFormat(lang === "en" ? "en-GB" : "tr-TR", {
      hour: "2-digit", minute: "2-digit", day: "2-digit", month: "2-digit",
      timeZone: "Europe/Istanbul",
    }).format(d);
  } catch (e) {
    return d.toISOString().slice(11, 16);
  }
}

// Hata metnini yenilenme saatiyle zenginleştirir. Saat yoksa metin
// olduğu gibi döner — uydurma saat yazmaktansa saatsiz kalmak yeğdir.
export function sinirMetni(t, hata, lang) {
  const taban = mapErr(t, hata && hata.message);
  const saat = yenilenmeSaati(hata, lang);
  if (!saat) return taban;
  return taban + " " + String(t.limitResetsAt || "Hakkın {t} itibarıyla yenilenir.")
    .replace("{t}", saat);
}

export function mapErr(t, msg) {
  if (!msg) return t.errGeneric || "Bir hata oluştu.";
  const m = String(msg);
  const em = t.errMap || {};

  // 🔴 v2.38 — AG HATASI "BIR HATA OLUSTU" DEGILDIR.
  // Baglanti koptugunda Supabase istemcisi "Network request failed" /
  // "Failed to fetch" / "TypeError: Network request failed" firlatiyordu
  // ve biz bunu bilinmeyen hata sayip "Bir hata oluştu" diyorduk.
  //
  // Kullanici acisindan fark buyuk: "bir hata oluştu" = uygulama bozuk,
  // tekrar denemenin anlami yok. Oysa dogru mesaj "internetin gitti,
  // tekrar dene" — kullanici NE YAPACAGINI bilir.
  //
  // Bunu tek tek 134 catch blogunda degil, HERKESIN GECTIGI yerde
  // yakaliyoruz: hata cevirisi zaten burada merkezileşmis.
  // 🔴 `timed out` ile `timeout` AYRI yazimlar. Testim gercek
  // FetchError metnini kullandigi icin bunu yakaladi — desen
  // yazarken 'nasil yazilir' diye dusunmustum, 'nasil yaziliyor'
  // diye bakmam gerekiyordu.
  if (/network request failed|failed to fetch|networkerror|network error|time(d)? ?out|ETIMEDOUT|ENOTFOUND|ECONNREFUSED|ECONNRESET|socket hang up|aborted|offline/i.test(m)) {
    // Kaydet: "kac kullanici baglanti sorunu yasiyor" sorusunun cevabi
    // yalniz burada uretiliyor. Kullaniciya gosterdigimiz mesaj
    // dostane; bize dusen kayit ise sayisal.
    logError("network", m, "offline");
    return t.errOffline || "Bağlantı kurulamadı. İnternetini kontrol edip tekrar dene.";
  }
  // Supabase oturum yenileme hatasi: kullanici "cikis yaptim mi?" diye
  // sasirir; net soyle.
  if (/refresh token|jwt expired|invalid claim/i.test(m)) {
    // Oturum dusmesi sik olursa bu bir YAPILANDIRMA sorunudur
    // (token omru, saat kaymasi). Saymadan fark edilemez.
    logError("session", m, "expired");
    return t.errSession || "Oturumun sona ermiş. Tekrar giriş yapman gerekiyor.";
  }
  if (em[m]) return em[m];                                   // birebir kod
  const code = m.split(/[\s:]/).map(x => x.replace(/[^a-z_]/g, "")).find(x => em[x]);
  if (code && em[code]) return em[code];                     // bilinen kod
  // 🔴 23 EYLÜL — `e_*` SÖZLÜĞÜ HİÇ OKUNMUYORDU.
  // `hata_mesaji_check.py` bir kodu "karşılığı var" saymak için `errMap`
  // YA DA `e_*` anahtarına bakıyor; bu fonksiyon ise yalnız `errMap`e
  // bakıyordu. Denetim yeşil, kullanıcı "Bir şeyler ters gitti" görüyordu:
  // `session_closed`, `not_completed`, `no_matching_trip`,
  // `contact_not_verified`, `blocked_pair` … 22 kod (uçtan uca denetim).
  // Yalnız 7 çağrı yeri `t["e_"+kod]`a kendisi bakıyordu.
  // 🆕 SINIF: "BİR DENETİMİN 'KARŞILANDI' SAYDIĞI ŞEY, KODUN GERÇEKTEN
  // OKUDUĞU ŞEY DEĞİLSE, DENETİM KAPSAMI DEĞİL SÖZLÜĞÜ ÖLÇÜYORDUR."
  const eKod = m.split(/[\s:]/).map(x => x.replace(/[^a-z_0-9]/g, "")).find(x => x && t["e_" + x]);
  if (eKod) return t["e_" + eKod];
  // Bilinmeyen/ham DB hatası (İngilizce Postgres mesajı gibi) → kullanıcıya
  // Türkçe genel mesaj göster. Ham mesajı geliştirme için konsola yaz.
  if (typeof console !== "undefined") console.warn("[mapErr] eşleşmeyen hata:", m);
  // Bilinmeyen bir DB/ağ hatası = potansiyel sessiz kırılma. Üretimde
  // görebilmek için kaydet (SQL 063). Kullanıcıya Türkçe genel mesaj döner.
  // 🔴 v2.39 — HATA KAYDI YALNIZ "CEVIREMEDIGIM" HATALARI TUTUYORDU.
  // logError bu projede v1.63'te yazildi (SQL 063 + app_errors tablosu)
  // ama TEK cagirani buydu: bilinmeyen hata dalinda. Yani canlida en cok
  // bilmek istedigimiz seyler — kac kez ag koptu, kac istek reddedildi,
  // kac oturum dustu — hic kaydedilmiyordu.
  //
  // Sentry aramaya gerek yok: kendi sistemimiz zaten var, sadece
  // BAGLANMAMIS. Ucuncu bir servise para vermeden once elimizdekini
  // calistirmak gerek.
  logError("mapErr", m);
  return t.errGeneric || "Bir şeyler ters gitti. Lütfen tekrar dene.";
}

